// Quick helper to resolve either slug or ID
export const getCourseSeo = (identifier?: string): CourseSeoItem | undefined => {
  if (!identifier) return undefined;
  // Match by ID
  if (COURSE_SEO_DATA[identifier]) return COURSE_SEO_DATA[identifier];
  // Match by Slug
  return Object.values(COURSE_SEO_DATA).find((item) => item.slug === identifier);
};

export const getWorkshopSeo = (identifier?: string): CourseSeoItem | undefined => {
  if (!identifier) return undefined;
  if (WORKSHOP_SEO_DATA[identifier]) return WORKSHOP_SEO_DATA[identifier];
  return Object.values(WORKSHOP_SEO_DATA).find((item) => item.slug === identifier);
};

// Map slug to Mongo ID
export const resolveCourseId = (identifier?: string): string => {
  if (!identifier) return "";
  const match = getCourseSeo(identifier);
  return match ? match.id : identifier;
};

// Map Mongo ID to friendly slug URL
export const getCourseUrl = (idOrSlug?: string): string => {
  if (!idOrSlug) return "/course";
  const item = getCourseSeo(idOrSlug);
  return item ? `/course/details/${item.slug}` : `/course/details/${idOrSlug}`;
};
